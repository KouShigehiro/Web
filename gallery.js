// ===== 渲染图库 =====
const params = new URLSearchParams(window.location.search);
const ocKey = params.get('oc') || 'Shigehiro';
const oc = OC_DATA[ocKey] || OC_DATA['Shigehiro'];

document.getElementById('ocTitle').textContent = oc.name + ' ' + oc.cn;
document.getElementById('ocSub').textContent = oc.desc + ' · 点击图片查看大图';
document.title = oc.name + ' 图库 | Shigehiro 茂宏';

// 收集所有图片用于灯箱
let allImages = [];

const detail = document.getElementById('galleryDetail');
oc.groups.forEach(group => {
    if (group.images.length === 0) return;
    const groupEl = document.createElement('div');
    groupEl.className = 'gallery-group';
    groupEl.innerHTML = `<h2 class="group-title"><i class="fas fa-folder-open"></i> ${group.label} <span class="group-count">${group.images.length}</span></h2>`;

    const grid = document.createElement('div');
    grid.className = 'photo-grid';
    group.images.forEach(src => {
        const idx = allImages.length;
        allImages.push(src);
        const item = document.createElement('div');
        item.className = 'photo-item';
        item.innerHTML = `<img src="${src}" alt="${oc.name}" loading="lazy" data-idx="${idx}">`;
        item.addEventListener('click', () => openLightbox(idx));
        grid.appendChild(item);
    });
    groupEl.appendChild(grid);
    detail.appendChild(groupEl);
});

// ===== 灯箱 =====
const lightbox = document.getElementById('lightbox');
const lbImage = document.getElementById('lbImage');
const lbCounter = document.getElementById('lbCounter');
const lbClose = document.getElementById('lbClose');
const lbPrev = document.getElementById('lbPrev');
const lbNext = document.getElementById('lbNext');
let currentIdx = 0;

function openLightbox(idx) {
    currentIdx = idx;
    lbImage.src = allImages[idx];
    lbCounter.textContent = `${idx + 1} / ${allImages.length}`;
    lightbox.classList.add('active');
    document.body.style.overflow = 'hidden';
}
function showPrev() {
    currentIdx = (currentIdx - 1 + allImages.length) % allImages.length;
    lbImage.src = allImages[currentIdx];
    lbCounter.textContent = `${currentIdx + 1} / ${allImages.length}`;
}
function showNext() {
    currentIdx = (currentIdx + 1) % allImages.length;
    lbImage.src = allImages[currentIdx];
    lbCounter.textContent = `${currentIdx + 1} / ${allImages.length}`;
}
function closeLightbox() {
    lightbox.classList.remove('active');
    document.body.style.overflow = '';
}

lbClose.addEventListener('click', closeLightbox);
lbPrev.addEventListener('click', showPrev);
lbNext.addEventListener('click', showNext);
lightbox.addEventListener('click', (e) => { if (e.target === lightbox || e.target.classList.contains('lb-stage')) closeLightbox(); });
document.addEventListener('keydown', (e) => {
    if (!lightbox.classList.contains('active')) return;
    if (e.key === 'Escape') closeLightbox();
    if (e.key === 'ArrowLeft') showPrev();
    if (e.key === 'ArrowRight') showNext();
});
